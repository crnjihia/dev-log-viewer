#[derive(Debug, Clone, PartialEq)]
pub enum Operator {
    Colon, // substring or loose equality
    Equal,
    NotEqual,
    GreaterThan,
    GreaterThanOrEqual,
    LessThan,
    LessThanOrEqual,
}

#[derive(Debug, Clone, PartialEq)]
pub enum QueryValue {
    String(String),
    Number(f64),
    Bool(bool),
}

#[derive(Debug, Clone, PartialEq)]
pub enum Predicate {
    Comparison {
        field_path: String,
        op: Operator,
        val: QueryValue,
    },
    And(Box<Predicate>, Box<Predicate>),
    Or(Box<Predicate>, Box<Predicate>),
    Not(Box<Predicate>),
}

/// Token generated by the lexical scanner
#[derive(Debug, Clone, PartialEq)]
enum Token {
    Word(String),
    QuotedString(String),
    Colon,
    Equal,
    NotEqual,
    Gt,
    Gte,
    Lt,
    Lte,
    And,
    Or,
    Not,
    LParen,
    RParen,
}

#[derive(Debug, Clone)]
struct TokenWithPos {
    token: Token,
    pos: usize,
}

/// Lexical scanner for the structured query language
fn tokenize(input: &str) -> Result<Vec<TokenWithPos>, CoreError> {
    let mut tokens = Vec::new();
    let chars: Vec<(usize, char)> = input.char_indices().collect();
    let mut i = 0;

    while i < chars.len() {
        let (pos, ch) = chars[i];

        if ch.is_whitespace() {
            i += 1;
            continue;
        }

        if ch == '(' {
            tokens.push(TokenWithPos {
                token: Token::LParen,
                pos,
            });
            i += 1;
            continue;
        }

        if ch == ')' {
            tokens.push(TokenWithPos {
                token: Token::RParen,
                pos,
            });
            i += 1;
            continue;
        }

        if ch == ':' {
            tokens.push(TokenWithPos {
                token: Token::Colon,
                pos,
            });
            i += 1;
            continue;
        }

        if ch == '=' {
            tokens.push(TokenWithPos {
                token: Token::Equal,
                pos,
            });
            i += 1;
            continue;
        }

        if ch == '!' && i + 1 < chars.len() && chars[i + 1].1 == '=' {
            tokens.push(TokenWithPos {
                token: Token::NotEqual,
                pos,
            });
            i += 2;
            continue;
        }

        if ch == '>' {
            if i + 1 < chars.len() && chars[i + 1].1 == '=' {
                tokens.push(TokenWithPos {
                    token: Token::Gte,
                    pos,
                });
                i += 2;
            } else {
                tokens.push(TokenWithPos {
                    token: Token::Gt,
                    pos,
                });
                i += 1;
            }
            continue;
        }

        if ch == '<' {
            if i + 1 < chars.len() && chars[i + 1].1 == '=' {
                tokens.push(TokenWithPos {
                    token: Token::Lte,
                    pos,
                });
                i += 2;
            } else {
                tokens.push(TokenWithPos {
                    token: Token::Lt,
                    pos,
                });
                i += 1;
            }
            continue;
        }

        if ch == '"' || ch == '\'' {
            let quote = ch;
            let mut s = String::new();
            let mut j = i + 1;
            let mut closed = false;

            while j < chars.len() {
                let (_, c) = chars[j];
                if c == quote {
                    closed = true;
                    j += 1;
                    break;
                }
                s.push(c);
                j += 1;
            }

            if !closed {
                return Err(CoreError::QueryParse {
                    position: pos,
                    message: "Unterminated quoted string".into(),
                });
            }

            tokens.push(TokenWithPos {
                token: Token::QuotedString(s),
                pos,
            });
            i = j;
            continue;
        }

        // Read identifiers and unquoted words
        let start_pos = pos;
        let mut word = String::new();
        while i < chars.len() {
            let (_, c) = chars[i];
            if c.is_whitespace()
                || c == '('
                || c == ')'
                || c == ':'
                || c == '='
                || c == '!'
                || c == '>'
                || c == '<'
                || c == '"'
                || c == '\''
            {
                break;
            }
            word.push(c);
            i += 1;
        }

        if !word.is_empty() {
            let upper = word.to_uppercase();
            let tok = match upper.as_str() {
                "AND" => Token::And,
                "OR" => Token::Or,
                "NOT" => Token::Not,
                _ => Token::Word(word),
            };
            tokens.push(TokenWithPos {
                token: tok,
                pos: start_pos,
            });
        }
    }

    Ok(tokens)
}

struct Parser {
    tokens: Vec<TokenWithPos>,
    current: usize,
}

impl Parser {
    fn new(tokens: Vec<TokenWithPos>) -> Self {
        Self { tokens, current: 0 }
    }

    fn peek(&self) -> Option<&TokenWithPos> {
        self.tokens.get(self.current)
    }

    fn advance(&mut self) -> Option<TokenWithPos> {
        let tok = self.tokens.get(self.current).cloned();
        if tok.is_some() {
            self.current += 1;
        }
        tok
    }

    fn parse_expression(&mut self) -> Result<Predicate, CoreError> {
        self.parse_or()
    }

    fn parse_or(&mut self) -> Result<Predicate, CoreError> {
        let mut expr = self.parse_and()?;

        while let Some(tok) = self.peek() {
            if tok.token == Token::Or {
                self.advance();
                let right = self.parse_and()?;
                expr = Predicate::Or(Box::new(expr), Box::new(right));
            } else {
                break;
            }
        }

        Ok(expr)
    }

    fn parse_and(&mut self) -> Result<Predicate, CoreError> {
        let mut expr = self.parse_unary()?;

        while let Some(tok) = self.peek() {
            if tok.token == Token::And {
                self.advance();
                let right = self.parse_unary()?;
                expr = Predicate::And(Box::new(expr), Box::new(right));
            } else {
                break;
            }
        }

        Ok(expr)
    }

    fn parse_unary(&mut self) -> Result<Predicate, CoreError> {
        if let Some(tok) = self.peek() {
            if tok.token == Token::Not {
                self.advance();
                let inner = self.parse_unary()?;
                return Ok(Predicate::Not(Box::new(inner)));
            }
        }

        self.parse_primary()
    }

    fn parse_primary(&mut self) -> Result<Predicate, CoreError> {
        let last_pos = self.tokens.last().map(|t| t.pos).unwrap_or(0);
        let tok = self.advance().ok_or_else(|| CoreError::QueryParse {
            position: last_pos,
            message: "Unexpected end of query".into(),
        })?;

        if tok.token == Token::LParen {
            let expr = self.parse_expression()?;
            match self.advance() {
                Some(closing) if closing.token == Token::RParen => Ok(expr),
                Some(other) => Err(CoreError::QueryParse {
                    position: other.pos,
                    message: "Expected closing parenthesis ')'".into(),
                }),
                None => Err(CoreError::QueryParse {
                    position: tok.pos,
                    message: "Unclosed parenthesis".into(),
                }),
            }
        } else if let Token::Word(field_name) = tok.token {
            let op_tok = self.advance().ok_or_else(|| CoreError::QueryParse {
                position: tok.pos,
                message: format!("Expected operator after field '{}'", field_name),
            })?;

            let op = match op_tok.token {
                Token::Colon => Operator::Colon,
                Token::Equal => Operator::Equal,
                Token::NotEqual => Operator::NotEqual,
                Token::Gt => Operator::GreaterThan,
                Token::Gte => Operator::GreaterThanOrEqual,
                Token::Lt => Operator::LessThan,
                Token::Lte => Operator::LessThanOrEqual,
                _ => {
                    return Err(CoreError::QueryParse {
                        position: op_tok.pos,
                        message: format!(
                            "Expected comparison operator (:, =, !=, >, >=, <, <=), got {:?}",
                            op_tok.token
                        ),
                    });
                }
            };

            let val_tok = self.advance().ok_or_else(|| CoreError::QueryParse {
                position: op_tok.pos,
                message: "Expected comparison value after operator".into(),
            })?;

            let val = match val_tok.token {
                Token::QuotedString(s) => QueryValue::String(s),
                Token::Word(w) => {
                    if let Ok(num) = w.parse::<f64>() {
                        QueryValue::Number(num)
                    } else if w.eq_ignore_ascii_case("true") {
                        QueryValue::Bool(true)
                    } else if w.eq_ignore_ascii_case("false") {
                        QueryValue::Bool(false)
                    } else {
                        QueryValue::String(w)
                    }
                }
                _ => {
                    return Err(CoreError::QueryParse {
                        position: val_tok.pos,
                        message: "Expected string, number, or boolean value".into(),
                    });
                }
            };

            Ok(Predicate::Comparison {
                field_path: field_name,
                op,
                val,
            })
        } else {
            Err(CoreError::QueryParse {
                position: tok.pos,
                message: format!("Unexpected token {:?}", tok.token),
            })
        }
    }
}

/// Compiles a structured query string into an executable Predicate
pub fn compile_query(query: &str) -> Result<Predicate, CoreError> {
    let tokens = tokenize(query)?;
    if tokens.is_empty() {
        return Err(CoreError::QueryParse {
            position: 0,
            message: "Empty query string".into(),
        });
    }

    let mut parser = Parser::new(tokens);
    let pred = parser.parse_expression()?;

    if let Some(extra) = parser.peek() {
        return Err(CoreError::QueryParse {
            position: extra.pos,
            message: format!("Unexpected trailing token {:?}", extra.token),
        });
    }

    Ok(pred)
}

/// Recursively resolves a dot-separated field path (e.g. "Body.stkCallback.ResultCode") on a JSON Value
pub fn resolve_field<'a>(json: &'a Value, path: &str) -> Option<&'a Value> {
    let mut current = json;
    for part in path.split('.') {
        match current {
            Value::Object(map) => {
                current = map.get(part)?;
            }
            _ => return None,
        }
    }
    Some(current)
}

/// Evaluates a compiled Predicate against a JSON object
pub fn evaluate_predicate(predicate: &Predicate, json: &Value) -> bool {
    match predicate {
        Predicate::And(left, right) => {
            evaluate_predicate(left, json) && evaluate_predicate(right, json)
        }
        Predicate::Or(left, right) => {
            evaluate_predicate(left, json) || evaluate_predicate(right, json)
        }
        Predicate::Not(inner) => !evaluate_predicate(inner, json),
        Predicate::Comparison {
            field_path,
            op,
            val,
        } => {
            let field_val = match resolve_field(json, field_path) {
                Some(v) => v,
                None => return false,
            };

            match (op, val, field_val) {
                (Operator::Equal, QueryValue::String(expected), Value::String(actual)) => {
                    expected.eq_ignore_ascii_case(actual)
                }
                (Operator::Colon, QueryValue::String(expected), Value::String(actual)) => {
                    actual.to_lowercase().contains(&expected.to_lowercase())
                }
                (Operator::NotEqual, QueryValue::String(expected), Value::String(actual)) => {
                    !expected.eq_ignore_ascii_case(actual)
                }
                // Number comparisons
                (Operator::Equal, QueryValue::Number(expected), Value::Number(actual)) => actual
                    .as_f64()
                    .map(|a| (a - expected).abs() < f64::EPSILON)
                    .unwrap_or(false),
                (Operator::Colon, QueryValue::Number(expected), Value::Number(actual)) => actual
                    .as_f64()
                    .map(|a| (a - expected).abs() < f64::EPSILON)
                    .unwrap_or(false),
                (Operator::NotEqual, QueryValue::Number(expected), Value::Number(actual)) => actual
                    .as_f64()
                    .map(|a| (a - expected).abs() >= f64::EPSILON)
                    .unwrap_or(false),
                (Operator::GreaterThan, QueryValue::Number(expected), Value::Number(actual)) => {
                    actual.as_f64().map(|a| a > *expected).unwrap_or(false)
                }
                (
                    Operator::GreaterThanOrEqual,
                    QueryValue::Number(expected),
                    Value::Number(actual),
                ) => actual.as_f64().map(|a| a >= *expected).unwrap_or(false),
                (Operator::LessThan, QueryValue::Number(expected), Value::Number(actual)) => {
                    actual.as_f64().map(|a| a < *expected).unwrap_or(false)
                }
                (
                    Operator::LessThanOrEqual,
                    QueryValue::Number(expected),
                    Value::Number(actual),
                ) => actual.as_f64().map(|a| a <= *expected).unwrap_or(false),
                // Boolean comparisons
                (Operator::Equal, QueryValue::Bool(expected), Value::Bool(actual)) => {
                    expected == actual
                }
                (Operator::Colon, QueryValue::Bool(expected), Value::Bool(actual)) => {
                    expected == actual
                }
                (Operator::NotEqual, QueryValue::Bool(expected), Value::Bool(actual)) => {
                    expected != actual
                }
                // Loose string to number / number to string match
                (Operator::Colon, QueryValue::String(expected), Value::Number(actual)) => {
                    actual.to_string().contains(expected)
                }
                _ => false,
            }
        }
    }
}

/// Recursively scans JSON structures to extract unique field paths and inferred type names
pub fn extract_field_paths(val: &Value, prefix: &str, out: &mut BTreeMap<String, &'static str>) {
    match val {
        Value::Object(map) => {
            for (k, v) in map {
                let full_path = if prefix.is_empty() {
                    k.clone()
                } else {
                    format!("{}.{}", prefix, k)
                };
                extract_field_paths(v, &full_path, out);
            }
        }
        Value::String(_) => {
            out.insert(prefix.to_string(), "string");
        }
        Value::Number(_) => {
            out.insert(prefix.to_string(), "number");
        }
        Value::Bool(_) => {
            out.insert(prefix.to_string(), "boolean");
        }
        Value::Array(_) => {
            out.insert(prefix.to_string(), "array");
        }
        Value::Null => {
            out.insert(prefix.to_string(), "null");
        }
    }
}

/// Samples raw log lines and builds a sorted schema of available fields
pub fn sample_json_fields(lines: &[&str]) -> BTreeMap<String, &'static str> {
    let mut fields = BTreeMap::new();

    for line in lines {
        let trimmed = line.trim();
        if trimmed.starts_with('{') && trimmed.ends_with('}') {
            if let Ok(json) = serde_json::from_str::<Value>(trimmed) {
                extract_field_paths(&json, "", &mut fields);
            }
        }
    }

    fields
}

/// Executes a structured search over a memory-mapped file, streaming batches of matches.
pub fn search_json_mmap(
    view: &MmapView,
    index: &LineIndex,
    predicate: &Predicate,
    batch_tx: Option<&Sender<SearchBatch>>,
    cancel_token: Option<&Arc<AtomicBool>>,
    max_results: Option<usize>,
) -> Result<Vec<LineMeta>, CoreError> {
    if view.is_empty() {
        return Ok(Vec::new());
    }

    let bytes = view.as_slice();
    let (encoding, _) = detect_encoding(bytes);

    let is_cancelled = || {
        cancel_token
            .map(|t| t.load(Ordering::Relaxed))
            .unwrap_or(false)
    };

    let total_bytes = bytes.len();
    let total_lines = index.line_count();
    let max_matches = max_results.unwrap_or(usize::MAX);

    let mut all_matches = Vec::new();
    let mut batch_accumulator = Vec::new();

    let mut line_num: u64 = 0;
    let mut line_start: usize = 0;
    let mut search_pos: usize = 0;

    const BATCH_SIZE: usize = 100;

    while search_pos < total_bytes {
        if is_cancelled() {
            return Err(CoreError::Cancelled);
        }

        let line_end = match memchr(b'\n', &bytes[search_pos..]) {
            Some(idx) => search_pos + idx,
            None => total_bytes,
        };

        let mut raw_slice = &bytes[line_start..line_end];
        if let Some(stripped) = raw_slice.strip_suffix(b"\r") {
            raw_slice = stripped;
        }

        let trimmed_slice = raw_slice.trim_ascii();
        if trimmed_slice.starts_with(b"{") && trimmed_slice.ends_with(b"}") {
            if let Ok(json_val) = serde_json::from_slice::<Value>(trimmed_slice) {
                if evaluate_predicate(predicate, &json_val) {
                    let (decoded_text, _) = decode_lossy(raw_slice, encoding);
                    let level = LogLevel::detect_from_line(&decoded_text);

                    let meta = LineMeta {
                        line_number: line_num + 1,
                        byte_offset: line_start as u64,
                        byte_length: line_end.saturating_sub(line_start),
                        level,
                        text: decoded_text,
                        matches: Vec::new(),
                        is_truncated: false,
                    };

                    batch_accumulator.push(meta.clone());
                    all_matches.push(meta);

                    if batch_accumulator.len() >= BATCH_SIZE {
                        if let Some(tx) = batch_tx {
                            let _ = tx.send(SearchBatch {
                                matches: std::mem::take(&mut batch_accumulator),
                                lines_searched: line_num + 1,
                                total_lines,
                                is_done: false,
                            });
                        }
                    }

                    if all_matches.len() >= max_matches {
                        break;
                    }
                }
            }
        }

        line_num += 1;
        if line_end >= total_bytes {
            break;
        }
        line_start = line_end + 1;
        search_pos = line_start;
    }

    if let Some(tx) = batch_tx {
        let _ = tx.send(SearchBatch {
            matches: batch_accumulator,
            lines_searched: line_num,
            total_lines,
            is_done: true,
        });
    }

    Ok(all_matches)
}
